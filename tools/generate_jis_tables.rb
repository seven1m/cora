#!/usr/bin/env ruby
# Generate Cora's JIS mapping tables from MRI's transcode sources.
# Run from the repository root with ../ruby checked out:
#   ruby tools/generate_jis_tables.rb

ROOT = File.expand_path("..", __dir__)
SOURCE = File.join(ROOT, "../ruby/enc/trans/JIS")
OUTPUT = File.join(ROOT, "src/encoding/jis_tables.zig")
ENTRY = /^0x([0-9A-F]+) = 0x([0-9A-F]+)$/

def mappings(name)
  File.read(File.join(SOURCE, name)).scan(ENTRY).map do |a, b|
    [a.to_i(16), b.to_i(16)]
  end
end

def emit_array(lines, name, values, width)
  lines << "pub const #{name} = [_]u#{width}{"
  values.each_slice(12) do |chunk|
    lines << "    " + chunk.map { |value| format("0x%0#{width / 4}X", value) }.join(", ") + ","
  end
  lines << "};"
  lines << ""
end

lines = [
  "// Generated by tools/generate_jis_tables.rb from MRI's JIS transcode sources.",
  "// Do not edit these mappings by hand.",
  "",
]
[["JISX0208@1990", "jis0208"], ["JISX0212", "jis0212"]].each do |plane, label|
  decode = Array.new(94 * 94, 0)
  mappings("#{plane}%UCS.src").each do |jis, unicode|
    row, col = jis >> 8, jis & 0xFF
    raise "Invalid JIS code: #{jis.to_s(16)}" unless (0x21..0x7E).cover?(row) && (0x21..0x7E).cover?(col)
    raise "Unicode codepoint exceeds u16: #{unicode.to_s(16)}" unless unicode <= 0xFFFF

    decode[(row - 0x21) * 94 + col - 0x21] = unicode
  end
  encode = mappings("UCS%#{plane}.src").map { |unicode, jis| (unicode << 16) | jis }.sort
  raise "Duplicate Unicode mapping in #{plane}" unless encode.map { |entry| entry >> 16 }.uniq.length == encode.length

  emit_array(lines, "#{label}_to_unicode", decode, 16)
  emit_array(lines, "unicode_to_#{label}", encode, 32)
end

File.write(OUTPUT, lines.join("\n"))
